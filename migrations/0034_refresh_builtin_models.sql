-- Refresh the built-in catalog to GPT 5.5–6.1 and Claude 4.5–5.5.
-- Remove unused retired rows. Referenced rows remain disabled so requests,
-- conversations, channel mappings and immutable billing snapshots retain their IDs.
-- Match official legacy families only, not provider-prefixed custom aliases.
CREATE TABLE _catalog_retired_0034 AS
SELECT public_model_id FROM models WHERE
  public_model_id IN ('gpt-3', 'gpt-4', 'gpt-4o', 'gpt-5', 'claude-1', 'claude-2', 'claude-3')
  OR public_model_id GLOB 'gpt-[34][.-]*'
  OR public_model_id GLOB 'gpt-4o-*'
  OR public_model_id GLOB 'gpt-5-*'
  OR public_model_id GLOB 'gpt-5.[0-4]'
  OR public_model_id GLOB 'gpt-5.[0-4]-*'
  OR public_model_id GLOB 'claude-[123][.-]*'
  OR public_model_id GLOB 'claude-instant-*'
  OR public_model_id GLOB 'claude-*-3-*'
  OR public_model_id GLOB 'claude-*-4'
  OR public_model_id GLOB 'claude-*-4-[0-4]'
  OR public_model_id GLOB 'claude-*-4-[0-4]-*'
  OR public_model_id GLOB 'claude-*-4-20[0-9][0-9][0-9][0-9][0-9][0-9]';

DELETE FROM models
WHERE public_model_id IN (SELECT public_model_id FROM _catalog_retired_0034)
  AND NOT EXISTS (SELECT 1 FROM channel_models cm WHERE cm.public_model_id=models.public_model_id)
  AND NOT EXISTS (SELECT 1 FROM requests r WHERE r.public_model_id=models.public_model_id)
  AND NOT EXISTS (SELECT 1 FROM chat_conversations c WHERE c.model_id=models.public_model_id)
  AND NOT EXISTS (SELECT 1 FROM chat_messages m WHERE m.model_id=models.public_model_id);

UPDATE models SET status='disabled', price_version=price_version+1,
  updated_at=max(updated_at, CAST(strftime('%s', 'now') AS INTEGER) * 1000)
WHERE status='active' AND public_model_id IN (SELECT public_model_id FROM _catalog_retired_0034);

DROP TABLE _catalog_retired_0034;

