import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { BUILTIN_MODELS } from '../packages/model-catalog/index.ts';

const quote = value => `'${String(value).replaceAll("'", "''")}'`;
// Generate seed data for the current schema without rewriting historical migrations.
const timestamp = "CAST(strftime('%s', 'now') AS INTEGER) * 1000";
const path = new URL('../seeds/builtin-models.sql', import.meta.url);
const sql = '-- Generated by scripts/generate-model-seeds.mjs. Reference prices checked 2026-09-10.\n'
  + '-- Flat platform selling prices, not automatic provider tier pricing. Preserve existing configuration.\n'
  + BUILTIN_MODELS.map(model => `INSERT INTO models (public_model_id,status,sell_prices_json,price_version,created_at,updated_at)\nVALUES (${quote(model.id)},'active',${quote(JSON.stringify(model.prices))},1,${timestamp},${timestamp})\nON CONFLICT(public_model_id) DO NOTHING;\n`).join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) throw new Error('Built-in model seed differs from catalog.');
} else {
  mkdirSync(new URL('../seeds/', import.meta.url), { recursive: true });
  writeFileSync(path, sql);
}
