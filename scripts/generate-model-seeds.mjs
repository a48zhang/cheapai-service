import { readFileSync, writeFileSync } from 'node:fs';
import { BUILTIN_MODELS } from '../packages/model-catalog/index.ts';

const quote = value => `'${String(value).replaceAll("'", "''")}'`;
// Historical 0018 seed used 4096; migration 0019 drops the column.
const timestamp = "CAST(strftime('%s', 'now') AS INTEGER) * 1000";
const path = new URL('../migrations/0018_builtin_models.sql', import.meta.url);
const sql = '-- Generated by scripts/generate-model-seeds.mjs. Reference prices checked 2026-09-10.\n'
  + '-- Flat platform selling prices, not automatic provider tier pricing. Preserve existing configuration.\n'
  + BUILTIN_MODELS.map(model => `INSERT INTO models (public_model_id,status,sell_prices_json,price_version,admission_min_balance_units,max_output_tokens,default_output_tokens,created_at,updated_at)\nVALUES (${quote(model.id)},'active',${quote(JSON.stringify(model.prices))},1,0,${model.maxOutputTokens},4096,${timestamp},${timestamp})\nON CONFLICT(public_model_id) DO NOTHING;\n`).join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) throw new Error('Built-in model migration differs from catalog.');
} else {
  writeFileSync(path, sql);
}
