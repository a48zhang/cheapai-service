export const auditActionLabel = (action: string) => {
  if (auditActionLabels[action]) return auditActionLabels[action];
  const status = /^(channel\.test\.[a-z_]+)\.(\d{3})$/u.exec(action);
  return status && auditActionLabels[status[1]!]
    ? `${auditActionLabels[status[1]!]}（${status[2]}）`
    : action;
};
export const auditTargetLabel = (type: string) => auditTargetLabels[type] ?? type;
